/**
 * ═══ شرح للمناقشة: سقف الساعات حسب المعدل ═══
 * قاعدة تسجيل جامعية معروفة: كل ما المعدل التراكمي (GPA من 4) أعلى، الطالب
 * مسموح له ساعات أكتر في الترم:
 *   GPA > 3        → 18 ساعة (الحد الأقصى المطلق)
 *   2 <= GPA <= 3   → 16 ساعة
 *   GPA < 2         → 14 ساعة (إنذار أكاديمي، بيتقيّد أكتر)
 * الشرط بيتفحص من أعلى لأسفل (لو> 3 return فورًا)، فمفيش تداخل بين الحالات.
 * الدالة دي بتتنادى في مكانين: مرة في الواجهة (عشان تمنع الطالب من فوق)
 * ومرة تانية في السيرفر (POST /api/schedule) — التحقق في الواجهة بس مش
 * كفاية لأن أي حد يقدر يعدّل الطلب من الـ DevTools ويتخطاه، فلازم يتأكد
 * منه السيرفر كمان قبل ما يحفظ في قاعدة البيانات.
 */
export function maxCreditHoursForGpa(gpa: number): number {
  if (gpa > 3) return 18;
  if (gpa >= 2) return 16;
  return 14;
}
